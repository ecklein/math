"""Exact integer sum-of-squares certificate for the window-4 kernel separation (Lean: GRHPseudo.KernelSeparation).

Usage:  kernel_sos_certificate.py [--n 100] [--slack 0.002] [--sigma 10]
Writes  experiments/out/kernel_sos_certificate.json  and  lean/GRHPseudo/KernelSeparation/Data.lean.

Witness: the a = 1 LP kernel of kernel_certificate.py (79 nonnegative integer node values k_j, step h = 1/20 on [-2, 2]),
P(w) = sum_j k_j w^j.  We look for integers r_0..r_n, g_0..g_{2n} and D > 0 with

    |S(w)|^2 - D^2 |P(w)|^2 - |G(w)|^2 = E(w),   S = R^2,   E coefficient-dominated (E_0 >= 2 sum_{m>=1} |E_m|),

on the unit circle, where R(w) = sum r_j w^j, G(w) = sum g_j w^j and E's coefficients are the autocorrelations
acf(s) - D^2 acf(k) - acf(g).  Then D |P| <= |R|^2 on the circle, hence (Lean, integral_norm_paperFT_pwl_le)
(1/2pi) int |K^| <= sum r_j^2 / D, with no quadrature.

Construction (floats only choose the certificate; the check is exact integer arithmetic, here and in Lean):
  1. LP (HiGHS): cosine polynomial Q of degree n with Q >= |P| on a grid, minimizing q_0; add `slack` to q_0.
  2. Spectral factor (cepstral method, FFT): R real with |R|^2 = Q; round sigma*R to integers; D = sigma^2.
  3. T = acf(R^2) - D^2 acf(k) exactly; spectral factor of T - delta (delta = half its minimum); round to integers g.
  4. Check dominance of E exactly.
"""
import argparse
import json
import sys
from fractions import Fraction

import numpy as np
from scipy.optimize import linprog

sys.path.insert(0, "experiments")
from kernel_certificate import witness  # noqa: E402


def conv(a, b):
    out = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            out[i + j] += x * y
    return out


def acf(a):
    return [sum(a[j] * a[j + m] for j in range(len(a) - m)) for m in range(len(a))]


def spectral_factor(c, N):
    """c: cosine coefficients c_0..c_d of T = c_0 + 2 sum c_m cos(m theta) > 0. Returns real g, |g(e^{i theta})|^2 = T."""
    d = len(c) - 1
    full = np.zeros(N)
    full[: d + 1] = c
    full[N - d:] = c[1:][::-1]
    T = np.real(np.fft.fft(full))
    assert T.min() > 0, T.min()
    ce = np.fft.ifft(np.log(T)).real
    w = np.zeros(N)
    w[0] = 0.5
    w[1: N // 2] = 1
    w[N // 2] = 0.5
    g = np.fft.ifft(np.exp(np.fft.fft(ce * w))).real
    assert np.abs(g[d + 1: 2 * d + 2]).max() < 1e-9 * np.abs(g[: d + 1]).max()   # no truncation loss
    return g[: d + 1]


def build(n, slack, sigma):
    a, h, kj = witness("1.0")
    k = np.array(kj, float)
    t = np.linspace(0, np.pi, 8001)
    absP = np.abs(np.exp(1j * np.outer(t, np.arange(len(kj)))) @ k)
    C = np.hstack([np.ones((t.size, 1)), 2 * np.cos(np.outer(t, np.arange(1, n + 1)))])
    res = linprog(np.eye(n + 1)[0], A_ub=-C, b_ub=-absP, bounds=[(None, None)] * (n + 1), method="highs")
    assert res.status == 0, res.message
    q = res.x.copy()
    q[0] *= 1 + slack
    r = [int(round(x * sigma)) for x in spectral_factor(q, 1 << 15)]
    D = int(round(sigma * sigma))
    As, Ak = acf(conv(r, r)), acf(kj)
    T = [As[m] - D * D * (Ak[m] if m < len(Ak) else 0) for m in range(len(As))]
    scale = float(T[0])
    N = 1 << 16
    d = len(T) - 1
    full = np.zeros(N)
    full[: d + 1] = np.array(T, float) / scale
    full[N - d:] = np.array(T[1:][::-1], float) / scale
    tmin = np.real(np.fft.fft(full)).min()
    assert tmin > 0, tmin
    cT = np.array(T, float) / scale
    cT[0] -= tmin / 2
    g = [int(round(x * np.sqrt(scale))) for x in spectral_factor(cT, N)]
    Ag = acf(g)
    E = [T[m] - Ag[m] for m in range(len(T))]
    assert E[0] >= 2 * sum(abs(x) for x in E[1:]), "dominance fails"
    return kj, r, g, D, h


def lean_list(xs):
    out, line = [], "  ["
    for i, x in enumerate(xs):
        s = str(x) + (", " if i < len(xs) - 1 else "]")
        if len(line) + len(s) > 100:
            out.append(line.rstrip())
            line = "   "
        line += s
    out.append(line)
    return "\n".join(out)


LEAN_HEADER = '''import GRHPseudo.KernelSeparation.Poly

/-!
# Certificate data for the window-4 kernel (generated)

Generated by `experiments/kernel_sos_certificate.py` (n = {n}, slack = {slack}, sigma = {sigma}); do not edit by hand.

* `kData`: the 79 node values of the witness kernel (the `a = 1` LP solution of `experiments/kernel_lp.py`, rounded to
  nonnegative integers with maximum 10⁶; the same rounding as `experiments/kernel_certificate.py`).
* `rData`, `gData`, `dData`: the sum-of-squares certificate, checked by `certOK` in the kernel.
-/

namespace GRHPseudo.KernelSeparation

/-- Node values of the witness kernel. -/
def kData : List ℤ :=
{k}

/-- Coefficients of `R`; the majorant is `|R|²/D`. -/
def rData : List ℤ :=
{r}

/-- Coefficients of the auxiliary square `G`. -/
def gData : List ℤ :=
{g}

/-- The scale `D`. -/
def dData : ℤ := {D}

/-- The certificate check, by kernel evaluation (no `native_decide`). -/
theorem certOK_data : certOK kData rData gData dData = true := by decide +kernel

end GRHPseudo.KernelSeparation
'''

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=100)
    ap.add_argument("--slack", type=float, default=0.002)
    ap.add_argument("--sigma", type=float, default=10.0)
    args = ap.parse_args()
    kj, r, g, D, h = build(args.n, args.slack, args.sigma)
    q0 = Fraction(sum(x * x for x in r), D)
    # Lean-side lower bound for the mass uses e^{1/40} >= 3281/3200 and e^{79/40} <= e^2 * 40/41, e < 2.7182818286
    L = Fraction(3281, 3200)
    ev = Fraction(0)
    for x in reversed(kj):
        ev = x + L * ev
    e = Fraction(27182818286, 10 ** 10)
    c_formal = e * e * Fraction(40, 41) * q0 / (h * ev)
    info = dict(n=args.n, slack=args.slack, sigma=args.sigma, D=D, k=kj, r=r, g=g,
                q0=str(q0), c_formal_upper=float(c_formal))
    with open("experiments/out/kernel_sos_certificate.json", "w") as fh:
        json.dump(info, fh)
    with open("lean/GRHPseudo/KernelSeparation/Data.lean", "w") as fh:
        fh.write(LEAN_HEADER.format(n=args.n, slack=args.slack, sigma=args.sigma, k=lean_list(kj),
                                    r=lean_list(r), g=lean_list(g), D=D))
    print(f"degree n = {args.n}, D = {D}, sum r^2 / D = {float(q0):.4f}, lengths k/r/g = {len(kj)}/{len(r)}/{len(g)}")
    print(f"c(K) <= {float(c_formal):.6f} via the Lean-side numerics (target 9/8 = 1.125)")
